/**
 * Regenerates src/content/bank/files.ts from the JSON files on disk.
 *
 *   pnpm bank:index
 */

import fs from "node:fs";
import path from "node:path";

const ROOT = path.join(process.cwd(), "src/content/bank");

function walk(dir: string): string[] {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    return e.isDirectory() ? walk(p) : e.name.endsWith(".json") ? [p] : [];
  });
}

const files = walk(ROOT)
  .map((f) => path.relative(ROOT, f).split(path.sep).join("/"))
  .sort();
const name = (rel: string) =>
  rel
    .replace(/\.json$/, "")
    .split(/[/-]/)
    .map((w, i) => (i === 0 ? w : w[0].toUpperCase() + w.slice(1)))
    .join("");

const out = `/**
 * Every file of the task bank, by its path under src/content/bank.
 * Generated by \`pnpm bank:index\`; \`pnpm validate:content\` fails when a JSON file is missing here.
 */

${files.map((f) => `import ${name(f)} from "./${f}";`).join("\n")}

export const BANK_FILES: Record<string, unknown> = {
${files.map((f) => `  "${f}": ${name(f)},`).join("\n")}
};
`;
fs.writeFileSync(path.join(ROOT, "files.ts"), out);
console.log(`bank/files.ts: ${files.length} files`);
